-- AQ Alta Qualidade
-- Execute no SQL Editor do projeto Supabase pertencente ao proprietário.
-- Este script NÃO cria usuários, não configura gateway e não usa service_role.
-- Modelo inicial: catálogo público somente leitura; gestão restrita a administradores ativos.

begin;

create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'manager' check (role in ('owner','manager','catalog','orders')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.aq_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = (select auth.uid())
      and a.is_active = true
  );
$$;

create or replace function public.aq_has_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = (select auth.uid())
      and a.is_active = true
      and (a.role = 'owner' or a.role = any(allowed_roles))
  );
$$;

revoke all on function public.aq_is_admin() from public;
revoke all on function public.aq_has_role(text[]) from public;
grant execute on function public.aq_is_admin() to anon, authenticated;
grant execute on function public.aq_has_role(text[]) to authenticated;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  description text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  slug text not null unique,
  description text,
  sku text unique,
  price numeric(12,2) not null check (price >= 0),
  compare_at_price numeric(12,2) check (compare_at_price is null or compare_at_price >= price),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  image_url text,
  images jsonb not null default '[]'::jsonb,
  variants jsonb not null default '[]'::jsonb,
  is_active boolean not null default false,
  is_featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  shipping_address jsonb not null default '{}'::jsonb,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  shipping_total numeric(12,2) not null default 0 check (shipping_total >= 0),
  discount_total numeric(12,2) not null default 0 check (discount_total >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_status text not null default 'pending' check (payment_status in ('pending','approved','rejected','refunded')),
  order_status text not null default 'pending' check (order_status in ('pending','paid','processing','shipped','completed','cancelled')),
  payment_provider text,
  payment_reference text,
  tracking_code text,
  customer_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  sku text,
  variant jsonb not null default '{}'::jsonb,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.coupons (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  discount_type text not null check (discount_type in ('percentage','fixed')),
  discount_value numeric(12,2) not null check (discount_value > 0),
  minimum_subtotal numeric(12,2) not null default 0 check (minimum_subtotal >= 0),
  max_uses integer check (max_uses is null or max_uses >= 0),
  used_count integer not null default 0 check (used_count >= 0),
  starts_at timestamptz,
  expires_at timestamptz,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create index if not exists products_category_idx on public.products(category_id);
create index if not exists products_active_idx on public.products(is_active);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(order_status);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- Atualiza updated_at automaticamente em alterações.
create or replace function public.aq_touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $
begin
  new.updated_at = now();
  return new;
end;
$;

drop trigger if exists aq_touch_admin_users on public.admin_users;
create trigger aq_touch_admin_users before update on public.admin_users for each row execute function public.aq_touch_updated_at();
drop trigger if exists aq_touch_categories on public.categories;
create trigger aq_touch_categories before update on public.categories for each row execute function public.aq_touch_updated_at();
drop trigger if exists aq_touch_products on public.products;
create trigger aq_touch_products before update on public.products for each row execute function public.aq_touch_updated_at();
drop trigger if exists aq_touch_orders on public.orders;
create trigger aq_touch_orders before update on public.orders for each row execute function public.aq_touch_updated_at();
drop trigger if exists aq_touch_coupons on public.coupons;
create trigger aq_touch_coupons before update on public.coupons for each row execute function public.aq_touch_updated_at();

